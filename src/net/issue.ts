/**
 * 诊断导出 → 一键新建 GitHub Issue。
 * body = 人话模板（版本/OS/错误码），**不含任何 key**：
 * 前端再过一遍敏感模式正则（anthropic|openai|sk-|api[_-]?key）→ 脱敏替换。
 * 纯函数，可单测。
 */

export const ISSUE_NEW_URL = "https://github.com/imAiBOX/aibox-app/issues/new";

export interface IssueContext {
  version: string;
  os: string;
  /** 人话错误码（如 NET_ALL_CHANNELS_DEAD）；可空 */
  errorCode?: string;
  /** 当前语言构建的简短现象描述（人话，来自 i18n） */
  symptom?: string;
  /** 已导出的诊断 zip 文件名（不含路径）；可空 */
  diagFile?: string;
  lang?: "en" | "zh-CN";
}

/** 敏感模式：命中 → 脱敏（与 Rust diagzip 同规则，双保险） */
const SENSITIVE = /(anthropic|openai|sk-[A-Za-z0-9_-]+|api[_-]?key\s*[:=]\s*\S+)/gi;

export function redact(text: string): string {
  return text.replace(SENSITIVE, (m) => {
    if (/^sk-/i.test(m)) return "sk-****";
    return "[redacted]";
  });
}

function template(ctx: IssueContext): { title: string; body: string } {
  const zh = (ctx.lang ?? "en") === "zh-CN";
  const head = zh
    ? `【AiBOX 安装问题】${ctx.errorCode ?? ""}`.trim()
    : `[AiBOX install issue] ${ctx.errorCode ?? ""}`.trim();
  const lines = zh
    ? [
        "发生了什么（人话描述）：",
        ctx.symptom ?? "安装过程中出错了。",
        "",
        `版本：AiBOX v${ctx.version}`,
        `系统：${ctx.os}`,
        `错误码：${ctx.errorCode ?? "未知"}`,
        ctx.diagFile ? `诊断包：已导出 ${ctx.diagFile}（桌面），可作为附件上传` : "诊断包：未导出（可在错误页点「导出诊断」）",
        "",
        "备注：本 Issue 模板由安装器自动生成，不含任何 API key。",
      ]
    : [
        "What happened (plain words):",
        ctx.symptom ?? "The installer hit an error.",
        "",
        `Version: AiBOX v${ctx.version}`,
        `OS: ${ctx.os}`,
        `Error code: ${ctx.errorCode ?? "unknown"}`,
        ctx.diagFile
          ? `Diagnostic package: exported as ${ctx.diagFile} (Desktop) — attach it below`
          : "Diagnostic package: not exported (use “Export diagnostics” on the error page)",
        "",
        "Note: this template is generated by the installer and never includes API keys.",
      ];
  return { title: head, body: lines.join("\n") };
}

/** 构造预填 Issue URL（title/body 均过脱敏 + encodeURIComponent） */
export function buildIssueUrl(ctx: IssueContext): string {
  const { title, body } = template(ctx);
  const safeTitle = redact(title).slice(0, 100);
  const safeBody = redact(body);
  return `${ISSUE_NEW_URL}?title=${encodeURIComponent(safeTitle)}&body=${encodeURIComponent(safeBody)}`;
}
